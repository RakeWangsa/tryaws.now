/**
 * What the adapter needs and OpCtx does not carry: the catalog bundle. The blueprint is not in the
 * catalog row; the function that runs the adapter supplies it (VERIFY the id with
 * GetRelationalDatabaseBlueprints in tc-pool-dev). The customer id is never an input here.
 */
export interface DatabaseLaunchSpec {
  readonly bundleId: string;
  readonly blueprintId: string;
}
export interface DatabaseDeps {
  loadLaunch(input: { readonly productId: string }): Promise<DatabaseLaunchSpec | null>;
}

// Generated by the platform, never from customer text (R11). The master password is NOT sent:
// Lightsail generates it when it is omitted (VERIFY in tc-pool-dev). It is read on demand by the
// access-details function, shown once and never stored (U9, R14). This adapter never calls
// GetRelationalDatabaseMasterUserPassword and no step result, log or patch carries a password.
export const MASTER_DATABASE_NAME = "tcdb";
export const MASTER_USERNAME = "tcadmin";

const POLL_SECONDS = 15;
const MAX_WAIT_MS = 40 * 60 * 1000;

type Ctx = OpCtx<DatabaseConfig>;

const HOST_LABEL = "[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?";
const HOST = new RegExp(`^${HOST_LABEL}(?:\\.${HOST_LABEL}){1,7}$`);
const USERNAME = /^[A-Za-z][A-Za-z0-9_]{0,62}$/;

/**
 * The connection facts the customer needs (U6): the endpoint, the port and the master user name. Each
 * is stored only if it has the plain shape, else it is left out (R16). The password is never read here.
 */
function connectionFacts(found: {
  masterEndpoint?: { address?: string; port?: number };
  masterUsername?: string;
}): Record<string, unknown> {
  const out: Record<string, unknown> = {};
  const address = found.masterEndpoint?.address;
  const port = found.masterEndpoint?.port;
  if (typeof address === "string" && address.length <= 253 && HOST.test(address)) {
    out.endpointAddress = address;
  }
  if (typeof port === "number" && Number.isSafeInteger(port) && port >= 1 && port <= 65535) {
    out.endpointPort = port;
  }
  if (typeof found.masterUsername === "string" && USERNAME.test(found.masterUsername)) {
    out.masterUsername = found.masterUsername;
  }
  return out;
}

type Restore =
  | { readonly kind: "snapshot"; readonly snapshotName: string }
  | { readonly kind: "point_in_time"; readonly sourceName: string; readonly at: Date };

/**
 * WPU-G9. The payload of a restore names rows, never AWS names. A snapshot must be the customer's
 * own active backup of a database of the customer; a point in time must name the customer's own
 * database and an instant inside the retention window (R8, R11, R16). null = a plain create.
 */
async function restoreOf(ctx: Ctx): Promise<Restore | null> {
  const p = ctx.operation.payload;
  const payload = typeof p === "object" && p !== null ? (p as Record<string, unknown>) : {};
  const backupId = payload.restoreFromBackupId;
  const sourceId = payload.restoreSourceId;
  if (backupId === undefined && sourceId === undefined) return null;
  if (backupId !== undefined && sourceId !== undefined) throw fail("validation");
  const mine = (row: { customerId: string } | null): boolean =>
    row !== null && row.customerId === ctx.resource.customerId;
  if (backupId !== undefined) {
    if (!isUuid(backupId)) throw fail("validation");
    const backup = await ctx.owned(backupId);
    if (
      backup === null ||
      !mine(backup) ||
      backup.family !== "backup" ||
      backup.state !== "active" ||
      backup.parentResourceId === null
    ) {
      throw fail("validation");
    }
    const parent = await ctx.owned(backup.parentResourceId);
    if (parent === null || !mine(parent) || parent.family !== "database") throw fail("validation");
    return { kind: "snapshot", snapshotName: awsResourceName("snapshot", backup.id) };
  }
  if (!isUuid(sourceId) || typeof payload.restoreTime !== "string") throw fail("validation");
  const source = await ctx.owned(sourceId);
  if (
    source === null ||
    !mine(source) ||
    source.family !== "database" ||
    source.state === "destroyed"
  ) {
    throw fail("validation");
  }
  const at = new Date(payload.restoreTime);
  if (Number.isNaN(at.getTime())) throw fail("validation");
  const window = pointInTimeWindow(ctx.clock.now());
  if (at.getTime() < window.from.getTime() || at.getTime() > window.to.getTime()) {
    throw fail("validation");
  }
  return { kind: "point_in_time", sourceName: awsResourceName("database", source.id), at };
}

function fail(code: "validation" | "conflict" | "upstream_unavailable" | "internal"): AwsError {
  return new AwsError({ code, retryable: false });
}

async function orNull<T>(call: () => Promise<T>): Promise<T | null> {
  try {
    return await call();
  } catch (error) {
    if (error instanceof AwsError && error.code === "not_found") return null;
    throw error;
  }
}

const client = (ctx: Ctx): LightsailClient =>
  ctx.access.lightsail(ctx.account, ctx.region, "TcProvisioner");

const names = (id: string) => ({
  database: awsResourceName("database", id),
  snapshot: awsResourceName("snapshot", id),
});

function budget(ctx: Ctx): void {
  if (ctx.clock.now().getTime() - ctx.operation.createdAt.getTime() > MAX_WAIT_MS) {
    throw fail("upstream_unavailable");
  }
}

const pollAt = (ctx: Ctx): Date => new Date(ctx.clock.now().getTime() + POLL_SECONDS * 1000);

function hasTag(tags: readonly { key?: string; value?: string }[] | undefined, id: string) {
  return (tags ?? []).some((t) => t.key === "tc:resource" && t.value === id);
}

async function readDatabase(ctx: Ctx) {
  const got = await orNull(() =>
    client(ctx).send(
      new GetRelationalDatabaseCommand({
        relationalDatabaseName: names(ctx.resource.id).database,
      }),
    ),
  );
  return got?.relationalDatabase ?? null;
}

// A snapshot of this resource's backup child. A payload id is never turned into a name unless
// ctx.owned returned that row for this customer and it is a backup of this database (R8, R11).
async function ownedBackupName(ctx: Ctx): Promise<string> {
  const id = (ctx.operation.payload as { backupResourceId?: unknown } | null)?.backupResourceId;
  if (typeof id !== "string") throw fail("validation");
  const row = await ctx.owned(id);
  if (
    row === null ||
    row.family !== "backup" ||
    row.parentResourceId !== ctx.resource.id ||
    row.customerId !== ctx.resource.customerId
  ) {
    throw fail("validation");
  }
  return awsResourceName("snapshot", row.id);
}

export function createDatabaseAdapter(deps: DatabaseDeps): ProductAdapter<DatabaseConfig> {
  async function create(ctx: Ctx): Promise<StepResult> {
    const n = names(ctx.resource.id);
    switch (ctx.operation.step) {
      case null:
      case "create_database": {
        const found = await readDatabase(ctx);
        if (found !== null) {
          if (!hasTag(found.tags, ctx.resource.id)) throw fail("conflict");
          return stepNext("wait_available", { awsName: n.database });
        }
        const spec = await deps.loadLaunch({ productId: ctx.config.productId });
        if (spec === null) throw fail("validation");
        const orderId = (ctx.operation.payload as { orderId?: unknown } | null)?.orderId;
        const restore = await restoreOf(ctx);
        if (restore !== null) {
          // A NEW database from a snapshot or a point in time. It keeps the master user of the source;
          // the password is read on demand by access-details (U9).
          await client(ctx).send(
            new CreateRelationalDatabaseFromSnapshotCommand({
              relationalDatabaseName: n.database,
              availabilityZone: `${ctx.region}a`,
              relationalDatabaseBundleId: spec.bundleId,
              publiclyAccessible: false,
              ...(restore.kind === "snapshot"
                ? { relationalDatabaseSnapshotName: restore.snapshotName }
                : { sourceRelationalDatabaseName: restore.sourceName, restoreTime: restore.at }),
              tags: resourceTags({
                env: ctx.env,
                customerId: ctx.resource.customerId,
                resourceId: ctx.resource.id,
                orderId: orderId as string,
              }),
            }),
          );
          return stepNext("wait_available", { awsName: n.database });
        }
        await client(ctx).send(
          new CreateRelationalDatabaseCommand({
            relationalDatabaseName: n.database,
            availabilityZone: `${ctx.region}a`,
            relationalDatabaseBlueprintId: spec.blueprintId,
            relationalDatabaseBundleId: spec.bundleId,
            masterDatabaseName: MASTER_DATABASE_NAME,
            masterUsername: MASTER_USERNAME,
            publiclyAccessible: false,
            tags: resourceTags({
              env: ctx.env,
              customerId: ctx.resource.customerId,
              resourceId: ctx.resource.id,
              orderId: orderId as string,
            }),
          }),
        );
        return stepNext("wait_available", { awsName: n.database });
      }
      case "wait_available": {
        const found = await readDatabase(ctx);
        const state = found?.state;
        if (state === "available") {
          const facts = connectionFacts(found ?? {});
          return stepDone({
            state: "active",
            awsName: n.database,
            ...(Object.keys(facts).length > 0 ? { configMerge: facts } : {}),
          });
        }
        if (found === null || state === "creating" || state === undefined) {
          budget(ctx);
          return stepWait("wait_available", pollAt(ctx));
        }
        throw fail("upstream_unavailable");
      }
      default:
        throw fail("internal");
    }
  }

  // Stop and start share one shape: ask once, then poll until the wanted state.
  async function toggle(ctx: Ctx, want: "stopped" | "available", done: StepResult) {
    const waitStep = want === "stopped" ? "wait_stopped" : "wait_started";
    const step = ctx.operation.step;
    const found = await readDatabase(ctx);
    if (found === null) throw fail("validation");
    if (found.state === want) return done;
    if (step === null || step === "request") {
      const name = names(ctx.resource.id).database;
      if (want === "stopped" && found.state === "available") {
        await client(ctx).send(new StopRelationalDatabaseCommand({ relationalDatabaseName: name }));
      } else if (want === "available" && found.state === "stopped") {
        await client(ctx).send(
          new StartRelationalDatabaseCommand({ relationalDatabaseName: name }),
        );
      }
      return stepWait(waitStep, pollAt(ctx));
    }
    if (step !== waitStep) throw fail("internal");
    const transient = ["stopping", "starting", "modifying", "backing-up", "available", "stopped"];
    if (!transient.includes(found.state ?? "")) throw fail("upstream_unavailable");
    budget(ctx);
    return stepWait(waitStep, pollAt(ctx));
  }

  async function finalSnapshot(ctx: Ctx): Promise<StepResult> {
    const n = names(ctx.resource.id);
    const lightsail = client(ctx);
    const snap = await orNull(() =>
      lightsail.send(
        new GetRelationalDatabaseSnapshotCommand({ relationalDatabaseSnapshotName: n.snapshot }),
      ),
    );
    if (snap?.relationalDatabaseSnapshot !== undefined) {
      const state = snap.relationalDatabaseSnapshot.state;
      if (state === "available") return stepDone();
      if (state === "error" || state === "failed") throw fail("upstream_unavailable");
      budget(ctx);
      return stepWait("wait_snapshot", pollAt(ctx));
    }
    const found = await readDatabase(ctx);
    if (found === null) throw fail("validation");
    if (found.state === "stopped") {
      // VERIFY: a stopped database cannot be snapshotted, so it is started first.
      await lightsail.send(
        new StartRelationalDatabaseCommand({ relationalDatabaseName: n.database }),
      );
      return stepWait("snapshot", pollAt(ctx));
    }
    if (found.state !== "available") {
      budget(ctx);
      return stepWait("snapshot", pollAt(ctx));
    }
    await lightsail.send(
      new CreateRelationalDatabaseSnapshotCommand({
        relationalDatabaseName: n.database,
        relationalDatabaseSnapshotName: n.snapshot,
      }),
    );
    return stepWait("wait_snapshot", pollAt(ctx));
  }

  async function manualSnapshot(ctx: Ctx): Promise<StepResult> {
    const name = await ownedBackupName(ctx);
    const lightsail = client(ctx);
    const snap = await orNull(() =>
      lightsail.send(
        new GetRelationalDatabaseSnapshotCommand({ relationalDatabaseSnapshotName: name }),
      ),
    );
    if (snap?.relationalDatabaseSnapshot === undefined) {
      await lightsail.send(
        new CreateRelationalDatabaseSnapshotCommand({
          relationalDatabaseName: names(ctx.resource.id).database,
          relationalDatabaseSnapshotName: name,
        }),
      );
      return stepWait("wait_backup", pollAt(ctx));
    }
    const state = snap.relationalDatabaseSnapshot.state;
    if (state === "available") return stepDone();
    if (state === "error" || state === "failed") throw fail("upstream_unavailable");
    budget(ctx);
    return stepWait("wait_backup", pollAt(ctx));
  }

  async function destroy(ctx: Ctx): Promise<StepResult> {
    // The final snapshot was made by finalSnapshot (the lifecycle guard requires it), so none is
    // asked for here; a second one would collide with the name.
    try {
      await client(ctx).send(
        new DeleteRelationalDatabaseCommand({
          relationalDatabaseName: names(ctx.resource.id).database,
          skipFinalSnapshot: true,
        }),
      );
    } catch (error) {
      if (!(error instanceof AwsError && error.code === "not_found")) throw error;
    }
    return stepDone({ state: "destroyed" });
  }

  async function deleteSnapshot(ctx: Ctx, snapshotName: string): Promise<StepResult> {
    try {
      await client(ctx).send(
        new DeleteRelationalDatabaseSnapshotCommand({
          relationalDatabaseSnapshotName: snapshotName,
        }),
      );
    } catch (error) {
      if (!(error instanceof AwsError && error.code === "not_found")) throw error;
    }
    return stepDone();
  }

  async function action(kind: OperationKind, ctx: Ctx): Promise<StepResult> {
    switch (kind) {
      case "stop":
        return toggle(ctx, "stopped", stepDone({ state: "stopped" }));
      case "start":
        return toggle(ctx, "available", stepDone({ state: "active" }));
      case "create_backup":
        return manualSnapshot(ctx);
      case "delete_backup":
        return deleteSnapshot(ctx, await ownedBackupName(ctx));
      case "set_db_options": {
        // Backup window and public mode of the console (WPU-G7). The payload is input (R9, R16).
        const p = ctx.operation.payload;
        const payload = typeof p === "object" && p !== null ? (p as Record<string, unknown>) : {};
        const window = payload.backupWindow;
        const open = payload.publiclyAccessible;
        const maintenance = payload.maintenanceWindow;
        if (window === undefined && open === undefined && maintenance === undefined) {
          throw fail("validation");
        }
        if (window !== undefined && checkedBackupWindow(window) === null) throw fail("validation");
        if (open !== undefined && typeof open !== "boolean") throw fail("validation");
        if (maintenance !== undefined && checkedMaintenanceWindow(maintenance) === null) {
          throw fail("validation");
        }
        // Lightsail refuses a backup window and a maintenance window that overlap: the new value is
        // compared with the one that is stored for the other.
        const stored =
          typeof ctx.resource.config === "object" && ctx.resource.config !== null
            ? (ctx.resource.config as Record<string, unknown>)
            : {};
        const backupNow = (window ?? stored.backupWindow) as unknown;
        const maintNow = (maintenance ?? stored.maintenanceWindow) as unknown;
        if (
          typeof backupNow === "string" &&
          typeof maintNow === "string" &&
          (window !== undefined || maintenance !== undefined) &&
          windowsOverlap(backupNow, maintNow)
        ) {
          throw fail("validation");
        }
        if (ctx.resource.state !== "active") throw fail("conflict");
        await client(ctx).send(
          new UpdateRelationalDatabaseCommand({
            relationalDatabaseName: names(ctx.resource.id).database,
            ...(window !== undefined ? { preferredBackupWindow: window as string } : {}),
            ...(open !== undefined ? { publiclyAccessible: open } : {}),
            ...(maintenance !== undefined
              ? { preferredMaintenanceWindow: maintenance as string }
              : {}),
            applyImmediately: true,
          }),
        );
        return stepDone({
          configMerge: {
            ...(window !== undefined ? { backupWindow: window } : {}),
            ...(open !== undefined ? { publiclyAccessible: open } : {}),
            ...(maintenance !== undefined ? { maintenanceWindow: maintenance } : {}),
          },
        });
      }
      default:
        // Anything else is not built for this family: refuse (R16).
        throw fail("validation");
    }
  }

  return {
    family: "database",
    parseConfig(input: unknown): DatabaseConfig {
      const parsed = parseDatabaseConfig(input);
      if (!parsed.ok) throw fail("validation");
      return parsed.value;
    },
    aws: {
      create,
      suspend: (ctx) => toggle(ctx, "stopped", stepDone({ state: "suspended" })),
      resume: (ctx) => toggle(ctx, "available", stepDone({ state: "active" })),
      finalSnapshot,
      destroy,
      purgeSnapshots: (ctx) => deleteSnapshot(ctx, names(ctx.resource.id).snapshot),
      async describe(ctx): Promise<LiveState> {
        const found = await readDatabase(ctx);
        return { state: found?.state ?? "missing" };
      },
      action,
    },
  };
}
