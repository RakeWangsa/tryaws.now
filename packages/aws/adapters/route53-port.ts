// The part of Amazon Route 53 that the DNS adapter needs, as a port (WP7-T3).
//
// Route 53 client not built: dependency not installable offline. The real client (a later task) wraps
// @aws-sdk/client-route-53 behind this interface and reaches the tc-dns account through STS
// AssumeRole (TcDnsProvisioner for writes, TcDnsReader for reads; R3). Until then the adapter is tested
// against test/fake-route53.ts.
//
// Rules for an implementation (VERIFY each against the current Route 53 documentation):
// - `createHostedZone` is idempotent on `callerReference`: the same reference answers the zone that the
//   first call made, with `created: false`. CreateHostedZone with a used CallerReference fails with
//   HostedZoneAlreadyExists (HTTP 409) only, and the client then finds the zone itself. ConflictingDomainExists
//   is something else (a delegation set or VPC conflict) and stays a "conflict" (WPU-Z19, API reference).
// - `listRecordSets` follows the pagination (ListResourceRecordSets, 300 per page) and returns every set.
//   Names come back with a trailing dot, and "*" as "\052" (VERIFY).
// - `changeRecordSets` is ONE ChangeResourceRecordSets batch: all changes or none. At most 1,000 ResourceRecord
//   elements and 32,000 characters of Value, an UPSERT counted twice (route53-limits.ts, the quotas page); a
//   caller with more independent changes splits them (splitChangeBatches). CREATE of an existing set and DELETE
//   of a missing one fail the whole batch.
// - `deleteHostedZone` fails while the zone holds sets other than the apex NS and SOA.
// - A missing zone is an AwsError with code "not_found"; a refused change is code "conflict".

export interface R53RecordSet {
  /** With the trailing dot, as Route 53 spells it. */
  readonly name: string;
  readonly type: string;
  readonly ttl: number;
  /** Wire form: TXT and CAA quoted, MX/SRV "n n ... host". */
  readonly values: readonly string[];
}

export interface R53Change {
  readonly action: "CREATE" | "UPSERT" | "DELETE";
  readonly set: R53RecordSet;
}

export interface R53Zone {
  readonly id: string;
  /** With the trailing dot. */
  readonly name: string;
  readonly nameServers: readonly string[];
}

export interface Route53Port {
  createHostedZone(input: {
    readonly name: string;
    readonly callerReference: string;
    /** Generated by the platform, never customer text (R11). */
    readonly comment: string;
  }): Promise<{
    readonly zone: R53Zone;
    readonly created: boolean;
    /**
     * WPU-Z19: the id of the change of CreateHostedZone (ChangeInfo.Id without "/change/"), which `getChangeStatus`
     * follows to INSYNC; null when a repeat found the zone of an earlier call (that change is not known).
     */
    readonly changeId: string | null;
  }>;
  /**
   * WPU-Z19: GetChange. "pending" until the change reached every Route 53 name server, then "insync" (CreateHostedZone:
   * "the initial status of the hosted zone is PENDING ... When the NS and SOA records are available, the status of
   * the zone changes to INSYNC").
   */
  getChangeStatus(changeId: string): Promise<"pending" | "insync">;
  getHostedZone(hostedZoneId: string): Promise<R53Zone | null>;
  /**
   * WP7-T4: every zone whose name is exactly the domain name (ListHostedZonesByName follows its
   * pagination). More than one is possible; the caller decides which one is the registration's and
   * fails closed when it cannot tell (R16).
   */
  findHostedZonesByName(name: string): Promise<readonly R53Zone[]>;
  listRecordSets(hostedZoneId: string): Promise<readonly R53RecordSet[]>;
  changeRecordSets(hostedZoneId: string, changes: readonly R53Change[]): Promise<void>;
  deleteHostedZone(hostedZoneId: string): Promise<void>;
}
